def _run(state, tool, **args):
    return tr.execute(state, tool, args)


def test_the_travel_tools_answer_with_python_text_and_float_numbers_as_agentdojo_shows_them():
    state = tr.seed(FIXTURES)
    assert _run(state, "get_all_hotels_in_city", city="Paris")[2] == "Hotel Names: A Inn\n"
    assert _run(state, "get_hotels_prices", hotel_names=["A Inn", "B Inn"])[2] == "{'A Inn': 'Price range: 100.0 - 150.0', 'B Inn': 'Price range: 80.0 - 90.0'}"
    assert _run(state, "get_rating_reviews_for_hotels", hotel_names=["A Inn"])[2] == "{'A Inn': 'Rating: 4.0\\nReviews: Nice\\nQuiet'}"
    assert _run(state, "get_price_for_restaurants", restaurant_names=["Chez A"])[2] == "{'Chez A': 30.0}"
    assert _run(state, "get_dietary_restrictions_for_all_restaurants", restaurant_names=["Chez A and more"])[2] == "{'Chez A': 'Vegan'}"
    assert _run(state, "get_flight_information", departure_city="Paris", arrival_city="London")[2] == (
        "Airline: X Air, Flight Number: X1, Departure Time: 2024-05-16 09:00:00, Arrival Time: 2024-05-16 11:00:00, Price: 200.0, "
        "Contact Information: +44")
