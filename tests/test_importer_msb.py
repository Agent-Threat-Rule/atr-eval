def test_a_licence_commit_or_folder_that_is_not_the_reviewed_one_stops_the_import(tmp_path):
    root = _copy(tmp_path)
    (root / "LICENSE.txt").write_text("All rights reserved.\n", encoding="utf-8")
    with pytest.raises(SourceError, match="MIT"):
        read_source_info(root)
    with pytest.raises(SourceError, match="not an MSB"):
        read_source_info(tmp_path)
    with pytest.raises(SourceError, match="40-character"):
        read_source_info(FIXTURE, commit="abc")
    with pytest.raises(SourceError, match="reviewed against MSB commit"):
        read_source_info(FIXTURE, commit="0" * 40)
    other = _copy(tmp_path / "o")
    (other / "LICENSE.txt").write_text((other / "LICENSE.txt").read_text(encoding="utf-8").replace("Dongsen Zhang", "Someone Else"), encoding="utf-8")
    with pytest.raises(SourceError, match="not an MSB"):
        read_source_info(other)


