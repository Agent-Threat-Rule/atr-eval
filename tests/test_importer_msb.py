def test_writing_never_overwrites_or_deletes_what_it_did_not_write(tmp_path):
    result = import_msb(FIXTURE, COMMIT, goals=GOALS[:1])
    out = tmp_path / "out"
    written, left = write_result(result, out)
    assert sorted(p.name for p in written) == ["AT-9200-msb-pi-ssh-key.yaml", "AT-9210-msb-fe-ssh-key.yaml", "AT-9220-msb-ui-ssh-key.yaml",
                                              "README.md"] and left == []
    first = {p.name: p.read_bytes() for p in out.iterdir()}
    write_result(result, out)
    assert {p.name: p.read_bytes() for p in out.iterdir()} == first  # the same input gives the same bytes
    stale = out / "AT-9299-msb-pi-old.yaml"
    stale.write_text("# Generated by `atr-eval import msb`\nid: AT-9299\n")
    assert write_result(result, out)[1] == [stale] and stale.exists()
    (out / "README.md").write_text("mine")
    with pytest.raises(SourceError, match="not overwriting"):
        write_result(result, out)
    assert (out / "README.md").read_text() == "mine"


